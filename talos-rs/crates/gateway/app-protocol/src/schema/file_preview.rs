use ts_rs::TS;

use super::export;

fn declarations() -> Vec<(String, String)> {
    macro_rules! declarations {
        ($($kind:ty),+ $(,)?) => {
            vec![$((<$kind>::ident(), export::<$kind>())),+]
        };
    }
    declarations!(
        talos_types::FilePreviewDocument,
        talos_types::FilePreviewDocumentUnavailable,
        talos_types::FilePreviewSource,
        talos_types::FilePreviewMetadata,
        talos_types::FilePreviewPrepareRequest,
        talos_types::FilePreviewDescriptor,
        talos_types::FilePreviewReadRequest,
        talos_types::FilePreviewContent,
        talos_types::FilePreviewCloseRequest,
        talos_types::FilePreviewCloseResponse,
    )
}

pub(super) fn imports() -> String {
    let names = declarations()
        .into_iter()
        .map(|(name, _)| name)
        .collect::<Vec<_>>()
        .join(", ");
    format!("import type {{ {names} }} from \"./file-preview\";\nexport type {{ {names} }};\n\n")
}

pub fn generate_typescript() -> String {
    let mut output =
        String::from("// This file is generated by talos-app-protocol. Do not edit.\n\n");
    for (_, declaration) in declarations() {
        output.push_str(&declaration);
    }
    let output = output
        .trim_end()
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n");
    format!("{output}\n")
}
