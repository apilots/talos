use ts_rs::TS;

use super::export;

fn declarations() -> Vec<(String, String)> {
    macro_rules! declarations {
        ($($kind:ty),+ $(,)?) => {
            vec![$((<$kind>::ident(), export::<$kind>())),+]
        };
    }
    declarations!(
        talos_types::AutomationMode,
        talos_types::LoopSchedule,
        talos_types::GoalStatus,
        talos_types::GoalPauseReason,
        talos_types::LoopStatus,
        talos_types::LoopStopReason,
        talos_types::SessionGoal,
        talos_types::SessionLoop,
        talos_types::AutomationTurnOrigin,
        talos_types::AutomationInputOrigin,
        talos_types::SessionAutomationSnapshot,
        talos_types::SessionAutomationReadRequest,
        talos_types::AutomationListEntry,
        talos_types::AutomationListScope,
        talos_types::AutomationListRequest,
        talos_types::AutomationListResponse,
        talos_types::AutomationChangedNotification,
        talos_types::AutomationAction,
        talos_types::GoalAction,
        talos_types::LoopAction,
        talos_types::LoopWakeDecision,
        talos_types::AutomationRequest,
        talos_types::AutomationEffect,
        talos_types::AutomationControlResult,
        talos_types::AutomationObjectRef,
        talos_types::AutomationCommandDescriptor,
        talos_types::AutomationCommandCatalogRequest,
        talos_types::AutomationCommandCatalogResponse,
        talos_types::AutomationCommand,
        talos_types::AutomationCommandResolveRequest,
        talos_types::AutomationCommandResolveResponse,
        talos_types::BuiltinJobId,
        talos_types::BuiltinJobAction,
        talos_types::BuiltinJobOutcome,
        talos_types::BuiltinJobInfo,
        talos_types::BuiltinJobListRequest,
        talos_types::BuiltinJobListResponse,
        talos_types::BuiltinJobControlRequest,
    )
}

pub(super) fn imports() -> String {
    let names = declarations()
        .into_iter()
        .map(|(name, _)| name)
        .collect::<Vec<_>>()
        .join(", ");
    format!("import type {{ {names} }} from \"./automation\";\nexport type {{ {names} }};\n\n")
}

pub fn generate_typescript() -> String {
    let mut output = String::from(
        "// This file is generated by talos-app-protocol. Do not edit.\n\nimport type { ApiError } from \"./app-protocol\";\n\n",
    );
    for (_, declaration) in declarations() {
        output.push_str(&declaration);
    }
    let mut output = output
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n");
    output.truncate(output.trim_end().len());
    output.push('\n');
    output
}
