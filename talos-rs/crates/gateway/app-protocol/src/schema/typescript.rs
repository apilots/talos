use ts_rs::TS;

pub(super) fn export<T: TS>() -> String {
    format!("export {}\n\n", T::decl())
}

pub fn generate_worker_runtime_typescript() -> String {
    let mut output =
        String::from("// This file is generated by talos-app-protocol. Do not edit.\n\n");
    output.push_str(&export::<talos_types::WorkerRuntimeCandidate>());
    output.push_str(&export::<talos_types::WorkerRuntimeSettingsResponse>());
    output.push_str(&export::<talos_types::WorkerRuntimeConnection>());
    output.push_str(&export::<talos_types::WorkerRuntimeEdits>());
    output.push_str(&export::<talos_types::WorkerRuntimeProfile>());
    output.push_str(&export::<talos_types::WorkerRuntimeTiming>());
    output.push_str(&export::<talos_types::WorkerRuntimeBackend>());
    output.push_str(&export::<talos_types::WorkerKubernetesSettings>());
    output.push_str(&export::<talos_types::WorkerKubeconfigAuthentication>());
    output.push_str(&export::<talos_types::WorkerKubeconfigSource>());
    let output = output
        .trim_end()
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n");
    format!("{output}\n")
}
