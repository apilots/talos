use ts_rs::TS;

use super::export;

fn declarations() -> Vec<(String, String)> {
    macro_rules! declarations {
        ($($kind:ty),+ $(,)?) => {
            vec![$((<$kind>::ident(), export::<$kind>())),+]
        };
    }
    declarations!(
        talos_types::BrowserAction,
        talos_types::BrowserTabAction,
        talos_types::BrowserHostRequest,
        talos_types::BrowserHostOperation,
        talos_types::BrowserHostResponse,
        talos_types::BrowserHostElement,
        talos_types::BrowserHostPage,
        talos_types::BrowserHostTab,
        talos_types::BrowserHostCancel,
        talos_types::BrowserHostUpload,
        talos_types::BrowserHostFile,
        talos_types::BrowserDownloadReceipt,
    )
}

pub(super) fn imports() -> String {
    let names = declarations()
        .into_iter()
        .map(|(name, _)| name)
        .collect::<Vec<_>>()
        .join(", ");
    format!("import type {{ {names} }} from \"./browser\";\nexport type {{ {names} }};\n\n")
}

pub fn generate_typescript() -> String {
    let mut output = String::from(
        "// This file is generated by talos-app-protocol. Do not edit.\n\nimport type { BrowserTargetKind } from \"./app-protocol\";\n\n",
    );
    for (_, declaration) in declarations() {
        output.push_str(&declaration);
    }
    let output = output
        .trim_end()
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n");
    format!("{output}\n")
}
