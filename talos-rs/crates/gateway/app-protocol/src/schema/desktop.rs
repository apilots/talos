use ts_rs::TS;

use super::export;

fn declarations() -> Vec<(String, String)> {
    macro_rules! declarations {
        ($($kind:ty),+ $(,)?) => {
            vec![$((<$kind>::ident(), export::<$kind>())),+]
        };
    }
    declarations!(
        talos_types::DesktopMediaFrame,
        talos_types::DesktopStreamOpen,
        talos_types::DesktopStreamSend,
        talos_types::DesktopStreamClose,
        talos_types::DesktopWorkerIdentityResponse,
        talos_types::DesktopWorkerEnrollParams,
        talos_types::DesktopViewGrant,
        talos_types::DesktopOpenRequest,
    )
}

pub(super) fn imports() -> String {
    let names = declarations()
        .into_iter()
        .map(|(name, _)| name)
        .collect::<Vec<_>>()
        .join(", ");
    format!("import type {{ {names} }} from \"./desktop\";\nexport type {{ {names} }};\n\n")
}

pub fn generate_typescript() -> String {
    let mut output = String::from(
        "// This file is generated by talos-app-protocol. Do not edit.\n\nimport type { BrowserInputMode, NodeSystemInfo } from \"./app-protocol\";\n\n",
    );
    for (_, declaration) in declarations() {
        output.push_str(&declaration);
    }
    let mut output = output
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n");
    output.truncate(output.trim_end().len());
    output.push('\n');
    output
}
