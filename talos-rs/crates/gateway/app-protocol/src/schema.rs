pub fn json_value_schema(_generator: &mut schemars::gen::SchemaGenerator) -> Schema {
    Schema::Bool(true)
}

#[derive(Debug, Serialize, JsonSchema)]
pub struct AppProtocolSchemaRoot {
    pub jsonrpc_message: JsonRpcMessage,
    pub client_request: ClientRequest,
    pub client_request_params: ClientRequestParams,
    pub server_notification: ServerNotification,
    pub server_request: ServerRequest,
    pub error: AppServerErrorBody,
    pub event_envelope: ApplicationEventEnvelope,
    pub initialize_response: InitializeResponse,
    pub turn_start_response: TurnStartResponse,
    pub event_subscribe_response: EventSubscribeResponse,
}

pub fn generate_json_schema() -> String {
    let schema = schema_for!(AppProtocolSchemaRoot);
    let value = serde_json::to_value(schema).expect("schema should serialize");
    serde_json::to_string_pretty(&value).expect("schema should format")
}

