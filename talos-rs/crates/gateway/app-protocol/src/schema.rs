fn export<T: TS>() -> String {
    format!("export {}\n\n", T::decl())
}

pub fn string_schema() -> Schema {
    Schema::Object(SchemaObject {
        instance_type: Some(InstanceType::String.into()),
        ..Default::default()
    })
}

