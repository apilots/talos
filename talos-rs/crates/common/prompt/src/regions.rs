pub const PROMPT_ARCHITECTURE_VERSION: &str = "prompt_arch_v2";

#[derive(Debug, Clone, Copy)]
pub struct PromptSectionTemplate {
    pub kind: PromptSectionKind,
    pub stable_name: &'static str,
    pub title: &'static str,
    pub priority: RegionPriority,
    pub placement: RegionPlacement,
    pub role: &'static str,
    pub framing_prompt: &'static str,
    pub cache_scope: SectionCacheScope,
    pub tier: BudgetTier,
    pub required: bool,
    pub envelope_policy: RegionEnvelopePolicy,
    pub bootstrap_kind: Option<WorkspaceBootstrapFileKind>,
}

macro_rules! template {
    (
        $kind:expr,
        $stable_name:expr,
        $title:expr,
        $priority:expr,
        $placement:expr,
        $role:expr,
        $framing:expr,
        $cache_scope:expr,
        $tier:expr,
        $required:expr,
        $envelope_policy:expr,
        $bootstrap_kind:expr
    ) => {
        PromptSectionTemplate {
            kind: $kind,
            stable_name: $stable_name,
            title: $title,
            priority: $priority,
            placement: $placement,
            role: $role,
            framing_prompt: $framing,
            cache_scope: $cache_scope,
            tier: $tier,
            required: $required,
            envelope_policy: $envelope_policy,
            bootstrap_kind: $bootstrap_kind,
        }
    };
}

