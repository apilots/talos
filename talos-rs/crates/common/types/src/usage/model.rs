use schemars::JsonSchema;
use serde::{Deserialize, Serialize};
use ts_rs::TS;

/// Classifies why model token usage was produced.
#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq, JsonSchema, TS)]
#[serde(rename_all = "snake_case")]
pub enum ModelUsageKind {
    /// User-visible Session Turn execution.
    Turn,
    /// Explicit Session context compaction.
    Compact,
    /// Agent-owned Session title generation.
    Title,
    /// Agent-owned managed `MEMORY.md` maintenance.
    Memory,
    /// Agent-owned Daily Memory candidate formation.
    Dream,
}

impl ModelUsageKind {
    /// Returns whether this kind is valid for `InnerModelClient` calls.
    pub const fn is_inner(self) -> bool {
        matches!(self, Self::Title | Self::Memory | Self::Dream)
    }

    /// Returns the canonical storage and diagnostic value for this kind.
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Turn => "turn",
            Self::Compact => "compact",
            Self::Title => "title",
            Self::Memory => "memory",
            Self::Dream => "dream",
        }
    }
}

/// Token usage values shared by runs, sessions, history, and metrics.
#[derive(Debug, Clone, Default, Serialize, Deserialize, PartialEq, Eq, JsonSchema, TS)]
pub struct TokenUsage {
    /// Provider-reported input token count.
    pub input_tokens: u32,
    /// Tokens generated by the model.
    pub output_tokens: u32,
    /// Provider-reported total token count.
    pub total_tokens: u32,
    /// Tokens written into a Provider prompt cache when reported.
    #[serde(default)]
    #[ts(optional)]
    #[ts(type = "number | null")]
    pub cache_creation_input_tokens: Option<u32>,
    /// Tokens read from a Provider prompt cache when reported.
    #[serde(default)]
    #[ts(optional)]
    #[ts(type = "number | null")]
    pub cache_read_input_tokens: Option<u32>,
}

impl TokenUsage {
    /// Returns whether the Provider supplied any non-zero usage value.
    pub fn is_available(&self) -> bool {
        self.total_tokens > 0
            || self.input_tokens > 0
            || self.output_tokens > 0
            || self.cache_creation_input_tokens.unwrap_or_default() > 0
            || self.cache_read_input_tokens.unwrap_or_default() > 0
    }

    /// Saturating-adds another usage sample while preserving optional cache semantics.
    pub fn accumulate(&mut self, other: &Self) {
        self.input_tokens = self.input_tokens.saturating_add(other.input_tokens);
        self.output_tokens = self.output_tokens.saturating_add(other.output_tokens);
        self.total_tokens = self.total_tokens.saturating_add(other.total_tokens);
        self.cache_creation_input_tokens = sum_optional_tokens(
            self.cache_creation_input_tokens,
            other.cache_creation_input_tokens,
        );
        self.cache_read_input_tokens =
            sum_optional_tokens(self.cache_read_input_tokens, other.cache_read_input_tokens);
    }
}

/// Adds optional cache counters without converting two missing values into a measured zero.
fn sum_optional_tokens(left: Option<u32>, right: Option<u32>) -> Option<u32> {
    match (left, right) {
        (Some(left), Some(right)) => Some(left.saturating_add(right)),
        (Some(value), None) | (None, Some(value)) => Some(value),
        (None, None) => None,
    }
}
