#!/usr/bin/env python3
"""Snapshot/check canonical Sync v1 DTOs without a sibling build dependency."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SNAPSHOT = ROOT / 'contracts/talos-sync/metrics-v1'
OUTPUT = ROOT / 'talos-rs/crates/orchestration/sync/src/metrics_wire.rs'
FILES = {'dto.rs': 'crates/server/src/metrics/dto.rs',
         'schema.json': 'crates/server/schema/metrics-v1.schema.json'}


def digest(data):
    return hashlib.sha256(data).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, help='Explicit canonical talos-sync checkout')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = {name: (args.source / source if args.source else SNAPSHOT / name).read_bytes()
            for name, source in FILES.items()}
    schema = json.loads(data['schema.json'])
    if 'account' not in schema['properties']:
        raise ValueError('Expected the canonical MetricsContract schema')
    definitions = []
    for name in ['MetadataCounts', 'PeerMetrics', 'AccountMetrics']:
        match = re.search(r'(#\[derive\([^\n]+\)\]\n#\[serde\([^\n]+\)\]\npub struct '
                          + name + r' \{.*?\n\})', data['dto.rs'].decode(), re.S)
        if match is None:
            raise ValueError('Canonical DTO not found: ' + name)
        definitions.append(match[0].replace(', JsonSchema', ''))
    generated = ('// Generated by scripts/sync-metrics-contract.py; do not edit.\n'
                 '// Wire timestamps are milliseconds; product timestamps are seconds.\n'
                 'use serde::{Deserialize, Serialize};\n\n' + '\n\n'.join(definitions) + '\n')
    manifest = json.dumps({'repository': 'https://github.com/apilots/talos-sync', 'apiVersion': 1,
                           'sources': {name: {'path': FILES[name], 'sha256': digest(raw)}
                                       for name, raw in data.items()}}, indent=2) + '\n'
    expected = {SNAPSHOT / name: raw for name, raw in data.items()}
    expected[SNAPSHOT / 'manifest.json'] = manifest.encode()
    expected[OUTPUT] = generated.encode()
    for path, raw in expected.items():
        if args.check:
            if not path.exists() or path.read_bytes() != raw:
                raise ValueError('Stale Sync contract: ' + str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(raw)
    print('Sync Metrics v1 contract ' + ('verified' if args.check else 'generated'))


if __name__ == '__main__':
    main()
